function valid(s){return s && s.module==='dm-06' && s.version===1 && typeof s.answers==='object' && s.answers!==null && typeof s.confidence==='object' && s.confidence!==null && Array.isArray(s.checked) && typeof s.explanation==='string' && s.explanation.length<=20000 && questions.every(q=>(s.answers[q.id]===undefined || Number.isInteger(s.answers[q.id])&&s.answers[q.id]>=0&&s.answers[q.id]<5)&&(s.confidence[q.id]===undefined||['alta','media','baixa'].includes(s.confidence[q.id]))) && s.checked.every(id=>questions.some(q=>q.id===id)&&Number.isInteger(s.answers[id]));}
